import {test,expect} from './fixtures';
import ExcelJS from 'exceljs';
import {passRecord} from './helpers/review';

test('rule candidates follow live line capacity, survive Pass and explain omitted postal',async({page})=>{
 const workbook=new ExcelJS.Workbook(),sheet=workbook.addWorksheet('Source');
 sheet.addRow(['Name','Address1','Address2','Address3','Bank_Country']);
 sheet.addRow(['RULE CUSTOMER','100 EXAMPLE ROAD WITH LONG STREET NAME','SUITE NUMBER 500 WITH LONG BUILDING NAME','BOSTON MA 02110','US']);
 const response=await page.request.post('/api/batches',{multipart:{file:{name:'Rule selection.xlsx',mimeType:'application/octet-stream',buffer:Buffer.from(await workbook.xlsx.writeBuffer())}}});
 expect(response.status()).toBe(200);const batch=await response.json();
 await page.goto('/results');await page.evaluate(id=>localStorage.setItem('atlas-batch',id),batch.id);await page.reload();
 await page.locator('.records-card tbody tr').filter({hasText:'RULE CUSTOMER'}).click();
 await expect(page.getByLabel('Beneficiary name',{exact:true})).toBeEnabled();
 await page.getByTestId('review-hybrid-panel').locator('summary').filter({hasText:'Selected Hybrid rule candidates'}).click();
 const selected=page.getByRole('region',{name:'Selected Hybrid rule candidates'});
 await expect(selected).toContainText('1a → 2a → 2z → 3a');
 const output=page.getByTestId('review-hybrid-panel');
 await expect(output.locator('.hybrid-line-candidate')).toHaveText(['1a · Name','2a · Primary address','2z · Postal / state','3a · Country / town']);
 await page.locator('summary').filter({hasText:'Address priority & postal retention'}).click();
 const table=page.getByRole('table',{name:'Hybrid candidate selection decisions'});
 await expect(table.locator('[data-candidate="2z"]')).toHaveAttribute('data-decision','SELECTED');
 await expect(table.locator('[data-candidate="2c"]')).toHaveAttribute('data-decision','DROPPED');
 const longName='RULE CUSTOMER WITH A LONG SECOND NAME CONTINUATION';
 await page.getByLabel('Beneficiary name',{exact:true}).fill(longName);
 await expect(selected).toContainText('1a → 1b → 2a → 3a');
 await expect(selected).toContainText('UNSAVED PREVIEW');
 await expect(table.locator('[data-candidate="2z"]')).toHaveAttribute('data-decision','DROPPED');
 await expect(table.locator('[data-candidate="2z"]')).toContainText('higher-priority records');
 await expect(output.locator('.hybrid-line-candidate')).toHaveText(['1a · Name','1b · Name continuation','2a · Primary address','3a · Country / town']);
 await page.getByLabel('Primary address',{exact:true}).fill('');
 await expect(selected).toContainText('1a → 1b → 2z → 3a');
 await expect(table.locator('[data-candidate="2z"]')).toHaveAttribute('data-decision','SELECTED');
 await page.getByLabel('Primary address',{exact:true}).fill('100 EXAMPLE ROAD WITH LONG STREET NAME');
 const saved=await passRecord(page);expect(saved.hybrid.selectionAudit.selectedKeys).toEqual(['1a','1b','2a','3a']);
 expect(saved.source.Name).toBe('RULE CUSTOMER');
 await page.locator('.records-card tbody tr').filter({hasText:longName}).click();
 await page.getByTestId('review-hybrid-panel').locator('summary').filter({hasText:'Selected Hybrid rule candidates'}).click();
 await expect(selected).toContainText('1a → 1b → 2a → 3a');
 await expect(selected).not.toContainText('UNSAVED PREVIEW');
 await expect(page.getByLabel('Beneficiary name',{exact:true})).toBeDisabled();
 await page.locator('.drawer-body').evaluate(element=>element.scrollTo({top:0,behavior:'instant'}));
 await page.screenshot({path:'/workspace/work/hybrid-selected-candidates-v2-0-1.png'});
});
